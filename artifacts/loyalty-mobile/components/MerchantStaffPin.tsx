import React, { useEffect, useState } from "react";
import { AppState, Pressable, StyleSheet, Text, View } from "react-native";
import { useAuth } from "@clerk/expo";
import { getGetStaffPinQueryKey, useGetStaffPin } from "@workspace/api-client-react";
import { useColors } from "@/hooks/useColors";

export function MerchantStaffPin({ businessId }: { businessId: string }) {
  const colors = useColors();
  const { userId } = useAuth();
  const [revealed, setRevealed] = useState(false);
  const [now, setNow] = useState(Date.now());
  const query = useGetStaffPin(businessId, {
    query: {
      queryKey: [...getGetStaffPinQueryKey(businessId), userId],
      enabled: revealed,
      staleTime: 0,
      gcTime: 0,
      retry: false,
      refetchInterval: revealed ? 15_000 : false,
      refetchOnWindowFocus: true,
    },
  });
  useEffect(() => {
    const timer = setInterval(() => setNow(Date.now()), 1000);
    const subscription = AppState.addEventListener("change", state => {
      if (state !== "active") setRevealed(false);
      setNow(Date.now());
    });
    return () => { clearInterval(timer); subscription.remove(); };
  }, []);
  const remaining = query.data ? Math.max(0, Math.ceil((Date.parse(query.data.expiresAt) - now) / 1000)) : 0;
  useEffect(() => {
    if (revealed && query.data && remaining === 0) void query.refetch();
  }, [remaining, revealed, query.data?.expiresAt]);
  const hours = Math.floor(remaining / 3600);
  const minutes = Math.floor((remaining % 3600) / 60);
  const seconds = remaining % 60;
  return (
    <View style={[styles.card, { backgroundColor: colors.card, borderColor: colors.border }]}>
      <Text style={[styles.title, { color: colors.foreground }]}>Private staff approval code</Text>
      <Text style={[styles.warning, { color: colors.destructive }]}>
        Do not share this code with customers or anyone else. Authorized staff should enter it discreetly.
      </Text>
      <Text style={[styles.help, { color: colors.mutedForeground }]}>Randomly generated by LoyaltyHub. Changes every three hours.</Text>
      {revealed && (
        <>
          <Text testID="merchant-staff-pin" style={[styles.code, { color: colors.primary }]} accessibilityLabel="Current staff code">
            {!query.isError && remaining > 0 ? query.data?.pin : '••••'}
          </Text>
          <Text style={[styles.help, { color: colors.mutedForeground }]}>
            {query.isError ? 'Code unavailable. Check your connection and try again.' :
              remaining > 0 ? `Changes in ${hours}:${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}` : 'Getting a fresh code…'}
          </Text>
        </>
      )}
      <Pressable accessibilityRole="button" onPress={() => setRevealed(value => !value)} style={[styles.button, { backgroundColor: colors.secondary }]}>
        <Text style={{ color: colors.primary, fontFamily: 'Inter_600SemiBold' }}>{revealed ? 'Hide code' : 'Show private code'}</Text>
      </Pressable>
    </View>
  );
}

const styles = StyleSheet.create({
  card: { borderWidth: 1, borderRadius: 20, padding: 18, gap: 10 },
  title: { fontSize: 15, fontFamily: "Inter_700Bold" },
  warning: { fontSize: 12, lineHeight: 18, fontFamily: "Inter_600SemiBold" },
  help: { fontSize: 12, lineHeight: 18, fontFamily: "Inter_400Regular" },
  code: { fontSize: 36, letterSpacing: 10, fontFamily: "Inter_700Bold" },
  button: { minHeight: 44, alignItems: "center", justifyContent: "center", borderRadius: 12 },
});
